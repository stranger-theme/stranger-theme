#!/usr/bin/env node

// Generates the stranger-theme-palette npm package (palette/dist/) from shared/palettes.js
// and keeps palette/package.json at the root version.
const fs = require('node:fs');
const path = require('node:path');
const { allData } = require('../../scripts/build-spec');

const ROOT = path.join(__dirname, '..', '..');
const PKG_DIR = path.join(__dirname, '..');
const DIST = path.join(PKG_DIR, 'dist');
const HEADER = '// Generated by palette/scripts/build.js from shared/palettes.js. Do not edit.\n';

// BG -> bg, LineHighlight -> line-highlight, BGLighter -> bg-lighter
const kebab = key => key.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase();

// Flat { name: hex } for one variant: base and derived colours, then ansi-0..15.
function colours(v) {
  const out = {};
  for (const [k, hex] of Object.entries({ ...v.base, ...v.derived })) out[kebab(k)] = hex;
  Object.values(v.ansi).forEach((hex, i) => { out[`ansi-${i}`] = hex; });
  return out;
}

const declarations = v => Object.entries(colours(v)).map(([k, hex]) => `  --stranger-${k}: ${hex};`).join('\n');
const union = keys => keys.map(k => `'${k}'`).join(' | ');

function build() {
  const data = allData();
  const ids = Object.keys(data);
  const first = data[ids[0]];

  fs.rmSync(DIST, { recursive: true, force: true });
  for (const dir of ['css', 'shiki']) fs.mkdirSync(path.join(DIST, dir), { recursive: true });

  const write = (file, text) => fs.writeFileSync(path.join(DIST, file), text);
  write('palettes.json', JSON.stringify(data, null, 2) + '\n');
  write('index.js', `${HEADER}'use strict';\nconst palettes = require('./palettes.json');\nmodule.exports = { palettes, variants: Object.keys(palettes) };\n`);
  write('index.mjs', `${HEADER}import cjs from './index.js';\nexport const { palettes, variants } = cjs;\n`);
  write('index.d.ts', `${HEADER}export type VariantId = ${union(ids)};
export type BaseColorName = ${union(Object.keys(first.base))};
export type DerivedColorName = ${union(Object.keys(first.derived))};
export type AnsiColorName = ${union(Object.keys(first.ansi))};

export interface Variant {
  id: VariantId;
  name: string;
  displayName: string;
  /** Hex colours, #RRGGBB */
  base: Record<BaseColorName, string>;
  /** Hex colours, #RRGGBB or #RRGGBBAA */
  derived: Record<DerivedColorName, string>;
  /** ANSI colours 0-15 in order, #RRGGBB */
  ansi: Record<AnsiColorName, string>;
}

export declare const palettes: Record<VariantId, Variant>;
export declare const variants: VariantId[];
`);

  const tailwind = Object.fromEntries(ids.map(id => [id, colours(data[id])]));
  write('tailwind.js', `${HEADER}'use strict';\nmodule.exports = ${JSON.stringify({ colors: { stranger: tailwind } }, null, 2)};\n`);

  const cssHeader = '/* Generated by palette/scripts/build.js from shared/palettes.js. Do not edit. */\n';
  for (const id of ids) {
    write(`css/${id}.css`, `${cssHeader}:root {\n${declarations(data[id])}\n}\n`);
    fs.copyFileSync(path.join(ROOT, 'visual-studio-code', 'themes', `${id}-color-theme.json`), path.join(DIST, 'shiki', `${id}.json`));
  }
  write('css/all.css', cssHeader + ids.map(id => `[data-stranger-theme="${id}"] {\n${declarations(data[id])}\n}\n`).join('\n'));

  fs.copyFileSync(path.join(ROOT, 'LICENSE'), path.join(PKG_DIR, 'LICENSE'));
  const pkgFile = path.join(PKG_DIR, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
  pkg.version = require('../../package.json').version;
  fs.writeFileSync(pkgFile, JSON.stringify(pkg, null, 2) + '\n');
}

build();
console.log('Wrote palette/dist/');
